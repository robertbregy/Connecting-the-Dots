'use strict';
const assert=require('node:assert/strict');
const {calculateLayoutShiftMetrics:measure}=require('./performance_metrics.cjs');
const shift=(startTime,value,hadRecentInput=false)=>({startTime,value,hadRecentInput});
const near=(actual,expected)=>assert.ok(Math.abs(actual-expected)<1e-12,actual+' != '+expected);
assert.deepEqual(measure([]),{cls:0,observedLayoutShiftSum:0});
near(measure([shift(100,.04),shift(500,.03),shift(1300,.02)]).cls,.09);
const separate=measure([shift(100,.04),shift(600,.03),shift(1600,.06)]);
near(separate.cls,.07);near(separate.observedLayoutShiftSum,.13);
const longWindow=measure([0,900,1800,2700,3600,4500,5400].map(t=>shift(t,.02)));
near(longWindow.cls,.12);near(longWindow.observedLayoutShiftSum,.14);
const leadingZeros=measure([0,900,1800,2700,3600,4500,5400].map((time,index)=>shift(time,index<4?0:.1)));
near(leadingZeros.cls,.3);near(leadingZeros.observedLayoutShiftSum,.3);
const recent=measure([shift(100,.02),shift(500,.9,true),shift(1400,.03)]);
near(recent.cls,.03);near(recent.observedLayoutShiftSum,.05);
near(measure([shift(2000,.03),shift(100,.04),shift(600,.03)]).cls,.07);
assert.throws(()=>measure([shift(1,NaN)]),/Invalid layout-shift value/);
assert.throws(()=>measure([{startTime:1,value:.1}]),/Missing layout-shift input classification/);
console.log('PERFORMANCE_METRICS_PASS '+JSON.stringify({cases:9,definition:'maximum session window; gap <1000ms and duration <5000ms'}));
